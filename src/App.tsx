import { useState } from 'react';
import { AlertTriangle } from 'lucide-react';
import { useConsolidated, systemById } from './lib/data';
import { useNewsletter } from './lib/newsletter';
import { Header } from './components/Header';
import { Sidebar } from './components/Sidebar';
import { NewsletterModal } from './tabs/Newsletter';
import { SystemView } from './tabs/SystemView';
import { MultiPeriodView } from './components/MultiPeriodView';

/** Deep-link: /?edition=newsletter (or #newsletter) opens the newsletter straight away.
 *  Used by the monthly email render and shareable links. */
function wantsNewsletter(): boolean {
  if (typeof window === 'undefined') return false;
  const q = new URLSearchParams(window.location.search).get('edition') ?? '';
  const v = (q || window.location.hash.replace('#', '')).toLowerCase();
  return v === 'newsletter';
}

export default function App() {
  const state = useConsolidated();
  const newsletter = useNewsletter();
  const [systemId, setSystemId] = useState<string | null>(null);
  const [nlOpen, setNlOpen] = useState<boolean>(wantsNewsletter);

  if (state.status === 'loading') return <LoadingScreen />;
  if (state.status === 'error') return <ErrorScreen message={state.error} />;

  const data = state.data;
  // No overview landing — the dashboard opens on the first system and the left
  // sidebar is the only navigation. `systemId` falls back to the first system
  // until the viewer picks one.
  const activeId = systemId ?? data.systems[0]?.systemId ?? null;
  const selected = activeId ? systemById(data, activeId) : undefined;

  const openSystem = (id: string) => {
    setSystemId(id);
    if (typeof window !== 'undefined') window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  // Download PDF: open the newsletter modal, then the browser's print dialog.
  // The print stylesheet flattens the modal into a full-flow A4 document.
  const downloadPdf = () => {
    setNlOpen(true);
    if (typeof window !== 'undefined') window.setTimeout(() => window.print(), 300);
  };

  return (
    <div className={`flex min-h-screen flex-col${nlOpen ? ' print-only-newsletter' : ''}`}>
      <Header client={data.client} generatedAt={data.generatedAt} onOpenNewsletter={() => setNlOpen(true)} />

      <div className="mx-auto flex w-full max-w-6xl flex-1 flex-col md:flex-row">
        <Sidebar sectors={data.sectors} systems={data.systems} activeId={activeId} onSelect={openSystem} />

        <main className="min-w-0 flex-1 px-4 py-5 sm:px-6">
          {selected ? (
            selected.views && selected.views.length ? (
              // key by systemId so the period/metric toggles reset to each system's own
              // default when you switch dashboards (otherwise the selection sticks across
              // systems — e.g. a MoM system would force HF off its Weekly default).
              <MultiPeriodView key={selected.systemId} block={selected} />
            ) : (
              <SystemView key={selected.systemId} block={selected} />
            )
          ) : null}
        </main>
      </div>

      <NewsletterModal
        data={data}
        newsletter={newsletter}
        open={nlOpen}
        onClose={() => setNlOpen(false)}
        onSelect={(id) => {
          setNlOpen(false);
          openSystem(id);
        }}
        onDownloadPdf={downloadPdf}
      />
    </div>
  );
}

function LoadingScreen() {
  return (
    <div className="flex min-h-screen flex-col">
      <div className="border-b border-slate-200/80 bg-white/85 backdrop-blur-md">
        <div className="mx-auto flex max-w-6xl items-center justify-between px-4 py-3 sm:px-6">
          <div className="shimmer h-7 w-40" />
          <div className="shimmer h-7 w-28" />
        </div>
      </div>
      <main className="mx-auto w-full max-w-6xl flex-1 px-4 py-6 sm:px-6">
        <div className="shimmer mb-4 h-8 w-80 max-w-full" />
        <div className="shimmer mb-6 h-56 w-full rounded-2xl" />
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-3">
          {Array.from({ length: 3 }).map((_, i) => (
            <div key={i} className="shimmer h-44 w-full rounded-2xl" />
          ))}
        </div>
      </main>
    </div>
  );
}

function ErrorScreen({ message }: { message: string }) {
  return (
    <div className="grid min-h-screen place-items-center px-4">
      <div className="max-w-md rounded-2xl bg-white p-6 text-center shadow-card ring-1 ring-slate-200/70">
        <div className="mx-auto mb-3 grid h-11 w-11 place-items-center rounded-full bg-rose-50 text-rose-500">
          <AlertTriangle size={20} />
        </div>
        <h1 className="font-display text-lg font-bold text-slate-900">Couldn't load the dashboard</h1>
        <p className="mt-1.5 text-[13px] text-slate-500">{message}</p>
        <p className="mt-3 text-[12px] text-slate-400">
          The data file is generated by the refresh pipeline. If this persists, the latest run may not have completed.
        </p>
      </div>
    </div>
  );
}
